"""openspacehdl new and update: the project of a system (docs/design.md, sections 6.2 to 6.5).

    openspacehdl new <system>.composer.json [<dir>] [--hdl <export dir>]
    openspacehdl update [<dir>] [--from <system>.composer.json [--hdl <export dir>]] [--dry-run] [--restore]

A project has three classes of files:

- inputs: the saved system and its export (hdl/), written by the Composer and copied byte for byte;
- generated: the harness and its package (sim/tb/<system>_th*.vhd), regenerated by update;
- seeds: README.md, sim/run.py and the testbench (sim/tb/<system>_tb.vhd), written once by new and never again.

.openspacehdl/project.json records the package version, the lock, the inputs and the SHA-256 of the text generated
last for every generated file. update regenerates a generated file only when it is unchanged on disk; an edited file
is kept, the new text goes to <file>.new, and update reports it and exits with status 1. Taking over <file>.new
makes the file unchanged again.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import sys
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path
from string import Template

from openspacehdl import __version__, composer, generate
from openspacehdl.errors import OshError

MANIFEST = Path(".openspacehdl") / "project.json"
FORMAT = "openspacehdl-project"
VERSION = 1


class ProjectError(OshError):
    """The project cannot be written or updated."""


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _lock_line(lock) -> str:
    return f"Lock: website {lock.website_commit[:10]}, reference-systems {lock.refsys_tag}"


def _template(name: str, **values: str) -> str:
    text = resources.files("openspacehdl").joinpath(f"templates/{name}").read_text(encoding="utf-8")
    return Template(text).substitute(values)


def _md_header(source: str, lock_line: str) -> str:
    inner = generate.header("", source, lock_line, generated=False)
    return "<!--\n" + "".join(line.lstrip() + "\n" for line in inner.splitlines()) + "-->"


def files_of(system: composer.System, lock) -> tuple[dict[str, str], dict[str, str]]:
    """(generated, seeds): project path -> text, for a checked system."""
    e, source, line = system.entity, system.path.name, _lock_line(lock)
    vhdl_gen = generate.header("--", source, line, generated=True)
    generated = {
        f"sim/tb/{e}_th_pkg.vhd": generate.harness_package(system, vhdl_gen),
        f"sim/tb/{e}_th.vhd": generate.harness(system, vhdl_gen),
    }
    seeds = {
        "README.md": _template("README.md.tmpl", header=_md_header(source, line), entity=e, source=source,
                               version=__version__),
        "sim/run.py": _template("run.py.tmpl", header=generate.header("#", source, line, generated=False).rstrip(),
                                entity=e),
        f"sim/tb/{e}_tb.vhd": _template("tb.vhd.tmpl", header=generate.header("--", source, line,
                                                                                generated=False).rstrip(), entity=e),
    }
    return generated, seeds


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _copy_inputs(system: composer.System, dest: Path, recorded: dict[str, str] | None = None) -> dict[str, str]:
    """Copies the saved file and its export into the project; returns project path -> SHA-256.

    recorded: the inputs of the project before; an export file of it that the new export no longer has is removed
    when it is unchanged."""
    out = {}
    target = dest / system.path.name
    if system.path.resolve() != target.resolve():
        shutil.copyfile(system.path, target)
    out[system.path.name] = _sha(target.read_bytes())
    hdl = dest / "hdl"
    hdl.mkdir(exist_ok=True)
    for f in sorted(system.hdl.iterdir()):
        if f.is_file() and f.name.startswith(system.entity):
            if f.resolve() != (hdl / f.name).resolve():
                shutil.copyfile(f, hdl / f.name)
            out[f"hdl/{f.name}"] = _sha((hdl / f.name).read_bytes())
    for p, h in (recorded or {}).items():
        f = dest / p
        if p.startswith("hdl/") and p not in out and f.is_file() and _sha(f.read_bytes()) == h:
            f.unlink()
    return out


def _manifest(system: composer.System, lock, inputs: dict[str, str], generated: dict[str, str],
              seeds: list[str]) -> dict:
    return {
        "format": FORMAT, "version": VERSION, "package": __version__,
        "lock": {"website": lock.website_commit, "referenceSystems": lock.refsys_tag, "openLogic": lock.olo_tag},
        "system": system.entity, "composer": system.path.name,
        "inputs": dict(sorted(inputs.items())),
        "generated": {p: _sha(t.encode("utf-8")) for p, t in sorted(generated.items())},
        "seeds": sorted(seeds),
    }


def new(source: Path, dest: Path | None = None, *, hdl: Path | None = None, lock=None,
        schema_dir: Path | None = None) -> composer.System:
    """Writes the project of the system in source into dest (default: ./<system>); returns the checked system."""
    if lock is None:
        from openspacehdl.lock import load as load_lock

        lock = load_lock()
    system = composer.load(Path(source), hdl=hdl, lock=lock, schema_dir=schema_dir)
    dest = Path(dest) if dest else Path.cwd() / system.entity
    if dest.exists() and any(dest.iterdir()):
        raise ProjectError(f"{dest} is not empty; openspacehdl new writes only into a new or empty directory")
    dest.mkdir(parents=True, exist_ok=True)
    inputs = _copy_inputs(system, dest)
    generated, seeds = files_of(system, lock)
    for p, text in {**generated, **seeds}.items():
        _write(dest / p, text)
    _write(dest / MANIFEST, json.dumps(_manifest(system, lock, inputs, generated, list(seeds)), indent=2) + "\n")
    return system


@dataclass
class UpdateReport:
    """What update did, or would do with dry_run: lists of project paths."""

    written: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    edited: list[str] = field(default_factory=list)
    deleted: list[str] = field(default_factory=list)
    restored: list[str] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)
    kept_obsolete: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.edited and not self.kept_obsolete


def read_manifest(dest: Path) -> dict:
    f = dest / MANIFEST
    if not f.is_file():
        raise ProjectError(f"{dest} is not a project of openspacehdl: {MANIFEST.as_posix()} is missing")
    m = json.loads(f.read_text(encoding="utf-8"))
    if m.get("format") != FORMAT or m.get("version") != VERSION:
        raise ProjectError(f"{MANIFEST.as_posix()} has format {m.get('format')!r} version {m.get('version')!r}; this "
                           f"package reads {FORMAT} version {VERSION}")
    return m


def update(dest: Path | None = None, *, source: Path | None = None, hdl: Path | None = None, dry_run: bool = False,
           restore: bool = False, lock=None, schema_dir: Path | None = None) -> UpdateReport:
    """Regenerates the generated files of the project in dest (default: the current directory).

    source: a new saved system (and its export, hdl) to copy into the project first. The table of section 6.4 decides
    what happens to each generated file; seeds and the integrator's files are never touched."""
    dest = Path(dest) if dest else Path.cwd()
    m = read_manifest(dest)
    if lock is None:
        from openspacehdl.lock import load as load_lock

        lock = load_lock()
    if source is not None:
        system = composer.load(Path(source), hdl=hdl, lock=lock, schema_dir=schema_dir)
        if system.entity != m["system"]:
            raise ProjectError(f"{Path(source).name} is the system {system.entity}, the project is {m['system']}")
        if not dry_run:
            _copy_inputs(system, dest, m.get("inputs", {}))
            system = composer.load(dest / m["composer"], hdl=dest / "hdl", lock=lock, schema_dir=schema_dir)
    else:
        system = composer.load(dest / m["composer"], hdl=dest / "hdl", lock=lock, schema_dir=schema_dir)
    report = UpdateReport(warnings=list(system.warnings))
    generated, _ = files_of(system, lock)
    recorded = m["generated"]
    for p, text in sorted(generated.items()):
        f = dest / p
        if not f.exists():
            if p in recorded and not restore:
                report.deleted.append(p)
                continue
            (report.restored if p in recorded else report.written).append(p)
            if not dry_run:
                _write(f, text)
            continue
        on_disk = _sha(f.read_bytes())
        if on_disk != recorded.get(p, on_disk) or (p not in recorded and on_disk != _sha(text.encode("utf-8"))):
            # edited by the integrator, or a file of the integrator where a new generated file belongs
            report.edited.append(p)
            if not dry_run:
                _write(dest / (p + ".new"), text)
            continue
        if on_disk == _sha(text.encode("utf-8")):
            report.unchanged.append(p)
            continue
        report.written.append(p)
        if not dry_run:
            _write(f, text)
    for p in sorted(set(recorded) - set(generated)):
        f = dest / p
        if f.exists() and _sha(f.read_bytes()) == recorded[p]:
            report.removed.append(p)
            if not dry_run:
                f.unlink()
        elif f.exists():
            report.kept_obsolete.append(p)
    if not dry_run:
        # The manifest records the text generated last, also for an edited or deleted file: taking over <file>.new
        # makes the file unchanged for the next update, keeping an edit is reported again.
        inputs = _copy_inputs(system, dest, m.get("inputs", {}))
        new_m = _manifest(system, lock, inputs, generated, m.get("seeds", []))
        for p in report.kept_obsolete:
            new_m["generated"][p] = recorded[p]
        for p in report.edited:
            if p not in recorded:
                new_m["generated"].pop(p, None)
        _write(dest / MANIFEST, json.dumps(new_m, indent=2) + "\n")
    return report


def main_new(source: str, dest: str | None, hdl: str | None) -> int:
    try:
        system = new(Path(source), Path(dest) if dest else None, hdl=Path(hdl) if hdl else None)
    except OshError as e:
        print(f"openspacehdl: {e}", file=sys.stderr)
        return 1
    for w in system.warnings:
        print(f"openspacehdl: warning: {w}", file=sys.stderr)
    print(f"wrote the project of {system.entity} to {dest or system.entity}")
    return 0


def main_update(dest: str | None, source: str | None, hdl: str | None, dry_run: bool, restore: bool) -> int:
    try:
        r = update(Path(dest) if dest else None, source=Path(source) if source else None,
                   hdl=Path(hdl) if hdl else None, dry_run=dry_run, restore=restore)
    except OshError as e:
        print(f"openspacehdl: {e}", file=sys.stderr)
        return 1
    verb = "would write" if dry_run else "wrote"
    for w in r.warnings:
        print(f"openspacehdl: warning: {w}", file=sys.stderr)
    for title, items in ((verb, r.written), ("restored", r.restored), ("removed (no longer generated)", r.removed),
                         ("edited, kept; the new text is in <file>.new", r.edited),
                         ("deleted, not written again (--restore writes it)", r.deleted),
                         ("no longer generated but edited, kept", r.kept_obsolete)):
        for p in items:
            print(f"{title}: {p}")
    if not (r.written or r.restored or r.removed or r.edited or r.deleted or r.kept_obsolete):
        print("nothing to update")
    return 0 if r.ok else 1
